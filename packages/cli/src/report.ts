import type { CaseOutcome, EvalReport } from "./types.js";
import { pct, rate, worstFirst } from "./score.js";

const PROTOCOL = "docs/eval-protocol.md";

/**
 * The report leads with the false-block rate because that is the number that
 * decides whether anyone leaves the guard switched on, and it states the
 * detection gap rather than blending it away. See docs/decisions.md, "Why two
 * eval suites, and why leave out the obvious number?".
 */
export function renderReport(report: EvalReport, meta: { date: string }): string {
  const clean = report.suites.filter((s) => s.kind === "clean").flatMap((s) => s.cases);
  const detection = report.suites.filter((s) => s.kind === "detection").flatMap((s) => s.cases);
  const out: string[] = [];

  out.push("# Eval report");
  out.push("");
  // No date and no timing in the committed report. It used to carry both, so
  // every contributor who ran the suites got a diff that said nothing.
  out.push(
    `${clean.length} clean cases, ${detection.length} held-out detection cases, no network.`,
  );
  out.push("");
  out.push(
    `Generated by \`genui-guard test\`. The cases were written before the claim policy's implementation was read, and ${PROTOCOL} records what that constrains.`,
  );
  out.push("");

  // ---------------------------------------------------------------------------
  out.push("## False blocks, on legitimate components");
  out.push("");
  out.push(
    "This is the headline. Every case in the clean suite is a component a correct model would produce from correct data, and withholding one of those is the failure that gets a trust layer switched off.",
  );
  out.push("");
  out.push("| Measure | Rate | Limit | Cases |");
  out.push("| --- | --- | --- | --- |");
  out.push(
    `| False blocks | **${pct(report.falseBlockRate)}** | ${limit(report.thresholds.maxFalseBlockRate)} | ${clean.filter((c) => c.falseBlock).length} of ${clean.length} |`,
  );
  out.push(
    `| False modifications | ${pct(report.falseModificationRate)} | ${limit(report.thresholds.maxFalseModificationRate)} | ${clean.filter((c) => c.falseModification).length} of ${clean.length} |`,
  );
  out.push("");
  out.push(
    "A false block withheld the element. A false modification rendered it with something true taken out, which is the quieter of the two and the one the phase 2 badge bug was.",
  );
  out.push("");

  const cleanFailures = clean.filter((c) => !c.passed);
  if (cleanFailures.length > 0) {
    out.push("### Every clean case that did not pass untouched");
    out.push("");
    for (const c of worstFirst(cleanFailures)) out.push(...caseLines(c));
    out.push("");
  } else {
    out.push("Every clean case passed untouched.");
    out.push("");
  }

  out.push("#### Clean suite by family");
  out.push("");
  out.push(familyTable(clean, "passed untouched"));
  out.push("");

  // ---------------------------------------------------------------------------
  out.push("## Detection, on held-out cases");
  out.push("");
  out.push(
    `${countCaught(detection)} of ${detection.length} caught, ${pct(report.detectionRate)}. The per-family figures are the useful part, because a blended number hides which fabrications the deterministic checks cannot see.`,
  );
  out.push("");
  out.push("| Family | Caught | Rate |");
  out.push("| --- | --- | --- |");
  for (const [family, bucket] of sortedFamilies(report.detectionByFamily)) {
    out.push(
      `| ${family} | ${bucket.caught} of ${bucket.total} | ${pct(rate(bucket.caught, bucket.total))} |`,
    );
  }
  out.push("");

  const blind = sortedFamilies(report.detectionByFamily).filter(([, b]) => b.caught === 0);
  if (blind.length > 0) {
    out.push(
      `**The gap.** Nothing in ${blind.map(([f]) => `\`${f}\``).join(", ")} was caught at all. These are the families a keyword and regex checker has no way to see, and they stay in the suite with their zeros rather than being dropped from the denominator.`,
    );
    out.push("");
  }

  if (report.collateral > 0) {
    out.push(
      `**Caught, but not cleanly.** ${report.collateral} detection ${report.collateral === 1 ? "case" : "cases"} kept the user safe by a blunter route than the one a developer would choose, usually by withholding a whole card where removing one badge would have done. Listed below, and not counted against the false-block rate, since the input was not legitimate.`,
    );
    out.push("");
  }

  const missed = detection.filter((c) => !c.passed);
  if (missed.length > 0) {
    out.push("### Everything the guard missed");
    out.push("");
    for (const c of worstFirst(missed)) out.push(...caseLines(c));
    out.push("");
  }

  const collateral = detection.filter((c) => c.passed && c.collateral);
  if (collateral.length > 0) {
    out.push("### Caught by a blunter route than intended");
    out.push("");
    for (const c of collateral) {
      out.push(`- **${c.id}** — ${c.describe}`);
      for (const line of c.collateral ?? []) out.push(`  - ${line}`);
    }
    out.push("");
  }

  // ---------------------------------------------------------------------------
  out.push("## Thresholds");
  out.push("");
  if (report.failures.length === 0) {
    out.push("Every configured threshold held.");
  } else {
    out.push("This run fails its thresholds:");
    out.push("");
    for (const failure of report.failures) out.push(`- ${failure}`);
  }
  out.push("");
  out.push(
    "Thresholds are regression floors rather than quality targets. The false-block limit is the bar the project sets for itself; the rest sit just below a measured baseline so a drop fails loudly.",
  );
  out.push("");

  return out.join("\n");
}

function caseLines(c: CaseOutcome): string[] {
  const label = c.falseBlock
    ? "withheld"
    : c.falseModification
      ? "altered"
      : "not caught";
  const lines = [`- **${c.id}** (${label}) — ${c.describe}`];
  for (const failure of c.failures) lines.push(`  - ${failure}`);
  for (const reason of dedupe(c.reasons)) lines.push(`  - guard said: ${reason}`);
  return lines;
}

function dedupe(values: string[]): string[] {
  return [...new Set(values)];
}

function countCaught(cases: CaseOutcome[]): number {
  return cases.filter((c) => c.passed).length;
}

function sortedFamilies<T extends { total: number; caught?: number; passed?: number }>(
  byFamily: Record<string, T>,
): [string, T & { caught: number }][] {
  return Object.entries(byFamily)
    .map(([name, b]) => [name, { ...b, caught: b.caught ?? b.passed ?? 0 }] as [string, T & { caught: number }])
    .sort((a, b) => a[1].caught / a[1].total - b[1].caught / b[1].total || a[0].localeCompare(b[0]));
}

function familyTable(cases: CaseOutcome[], what: string): string {
  const byFamily: Record<string, { total: number; passed: number }> = {};
  for (const c of cases) {
    const bucket = (byFamily[c.family] ??= { total: 0, passed: 0 });
    bucket.total += 1;
    if (c.passed) bucket.passed += 1;
  }

  const rows = [`| Family | ${what} | Rate |`, "| --- | --- | --- |"];
  for (const [family, bucket] of sortedFamilies(byFamily)) {
    rows.push(
      `| ${family} | ${bucket.passed} of ${bucket.total} | ${pct(rate(bucket.passed, bucket.total))} |`,
    );
  }
  return rows.join("\n");
}

function limit(value: number | undefined): string {
  return value === undefined ? "none set" : pct(value);
}

/**
 * A suite that runs in 40ms should say so, rather than rounding itself to 0.0s.
 * Coarse on purpose below a second: the report is committed, and a file that
 * changes by a millisecond on every run trains people to ignore its diff.
 */
function duration(ms: number): string {
  return ms < 1000 ? `${Math.round(ms / 10) * 10}ms` : `${(ms / 1000).toFixed(1)}s`;
}

/** The pull request comment. Short, and leading with the same number. */
export function renderComment(report: EvalReport, meta: { date: string }): string {
  const clean = report.suites.filter((s) => s.kind === "clean").flatMap((s) => s.cases);
  const detection = report.suites.filter((s) => s.kind === "detection").flatMap((s) => s.cases);
  const blind = sortedFamilies(report.detectionByFamily).filter(([, b]) => b.caught === 0);

  const lines = [
    "### genui-guard evals",
    "",
    `**False blocks ${pct(report.falseBlockRate)}** on ${clean.length} legitimate components` +
      `${report.thresholds.maxFalseBlockRate !== undefined ? ` (limit ${pct(report.thresholds.maxFalseBlockRate)})` : ""}.` +
      ` False modifications ${pct(report.falseModificationRate)}.`,
    "",
    `Detection ${pct(report.detectionRate)} on ${detection.length} held-out cases.` +
      (blind.length > 0
        ? ` Nothing caught in ${blind.map(([f]) => `\`${f}\``).join(", ")}, which is the known gap.`
        : ""),
    "",
    report.failures.length === 0
      ? "Thresholds held."
      : `**Thresholds failed.**\n${report.failures.map((f) => `- ${f}`).join("\n")}`,
    "",
    `<sub>${meta.date} · ${clean.length + detection.length} cases · ${duration(report.durationMs)} · full report in \`evals/reports/latest.md\` · method in \`${PROTOCOL}\`</sub>`,
  ];

  return lines.join("\n");
}
